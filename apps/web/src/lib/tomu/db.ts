import { newClientId } from "@tomu/shared";
import { openDB, type DBSchema, type IDBPDatabase } from "idb";
import type { Change, DocRecord, Folder, LocalLabel, OutboxEntry, Settings, Snapshot } from "./types.ts";

export const DB_NAME = "tomu";

interface TomuDB extends DBSchema {
  docs: { key: string; value: DocRecord };
  outbox: {
    key: number;
    value: OutboxEntry;
    indexes: { byOp: [string, string]; byDoc: string };
  };
  tombstones: { key: string; value: { id: string } };
  labels: { key: string; value: LocalLabel };
  folders: { key: string; value: Folder };
  settings: { key: string; value: Settings };
}

const SETTINGS_KEY = "settings";
const STORES = ["docs", "outbox", "tombstones", "labels", "folders", "settings"] as const;

export class LocalStore {
  private queue: Promise<unknown> = Promise.resolve();

  private readonly db: IDBPDatabase<TomuDB>;

  private constructor(db: IDBPDatabase<TomuDB>) {
    this.db = db;
  }

  static async open(name: string = DB_NAME): Promise<LocalStore> {
    const db = await openDB<TomuDB>(name, 1, {
      upgrade(d) {
        d.createObjectStore("docs", { keyPath: "id" });
        const outbox = d.createObjectStore("outbox", { keyPath: "n", autoIncrement: true });
        outbox.createIndex("byOp", ["doc", "env.id"]);
        outbox.createIndex("byDoc", "doc");
        d.createObjectStore("tombstones", { keyPath: "id" });
        d.createObjectStore("labels", { keyPath: "id" });
        d.createObjectStore("folders", { keyPath: "id" });
        d.createObjectStore("settings");
      },
    });
    const tx = db.transaction("settings", "readwrite");
    if ((await tx.store.get(SETTINGS_KEY)) === undefined) {
      const fresh: Settings = {
        clientId: newClientId(),
        displayName: "",
        largeView: false,
        clockLast: 0,
        onboarded: false,
      };
      await tx.store.put(fresh, SETTINGS_KEY);
    }
    await tx.done;
    return new LocalStore(db);
  }

  async load(): Promise<Snapshot> {
    const tx = this.db.transaction([...STORES], "readonly");
    const [docs, outbox, tombstones, labels, folders, settings] = await Promise.all([
      tx.objectStore("docs").getAll(),
      tx.objectStore("outbox").getAll(),
      tx.objectStore("tombstones").getAllKeys(),
      tx.objectStore("labels").getAll(),
      tx.objectStore("folders").getAll(),
      tx.objectStore("settings").get(SETTINGS_KEY),
    ]);
    await tx.done;
    if (!settings) throw new Error("settings missing");
    // Records from before onboarding existed lack the field: a set name means the person already uses the app.
    const onboarded = settings.onboarded ?? settings.displayName !== "";
    // Store the derived value so a later name change cannot flip it.
    if (settings.onboarded === undefined) await this.commit({ settings: { onboarded } });
    return {
      docs,
      outbox,
      tombstones: new Set(tombstones),
      labels,
      folders,
      settings: { ...settings, onboarded },
    };
  }

  /** Applies all parts of the change atomically; calls are serialized in call order. */
  commit(change: Change): Promise<void> {
    const run = this.queue.then(() => this.apply(change));
    this.queue = run.catch(() => undefined);
    return run;
  }

  /** Closes after the queued commits ran, so a write started just before stop still lands. */
  async close(): Promise<void> {
    await this.queue;
    this.db.close();
  }

  private async apply(c: Change): Promise<void> {
    const tx = this.db.transaction([...STORES], "readwrite");
    try {
      // Only IDB requests are awaited here, otherwise the transaction would auto-close.
      for (const d of c.putDocs ?? []) await tx.objectStore("docs").put(d);
      for (const id of c.deleteDocs ?? []) await tx.objectStore("docs").delete(id);
      const outbox = tx.objectStore("outbox");
      // `n` is generated by IndexedDB (autoIncrement).
      for (const e of c.addOutbox ?? []) await outbox.add({ doc: e.doc, env: e.env } as OutboxEntry);
      for (const r of c.removeOutbox ?? []) {
        const key = await outbox.index("byOp").getKey([r.doc, r.id]);
        if (key !== undefined) await outbox.delete(key);
      }
      for (const doc of c.clearOutbox ?? []) {
        for (const key of await outbox.index("byDoc").getAllKeys(doc)) await outbox.delete(key);
      }
      for (const id of c.addTombstones ?? []) await tx.objectStore("tombstones").put({ id });
      for (const l of c.putLabels ?? []) await tx.objectStore("labels").put(l);
      for (const id of c.deleteLabels ?? []) await tx.objectStore("labels").delete(id);
      for (const f of c.putFolders ?? []) await tx.objectStore("folders").put(f);
      for (const id of c.deleteFolders ?? []) await tx.objectStore("folders").delete(id);
      if (c.settings) {
        const settings = tx.objectStore("settings");
        const current = await settings.get(SETTINGS_KEY);
        if (!current) throw new Error("settings missing");
        await settings.put({ ...current, ...c.settings }, SETTINGS_KEY);
      }
    } catch (err) {
      try {
        tx.abort();
      } catch {
        // already finished
      }
      await tx.done.catch(() => undefined);
      throw err;
    }
    await tx.done;
  }
}
